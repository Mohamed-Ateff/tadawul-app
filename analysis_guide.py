def _step(n: int, text: str) -> str:
    return (f"<div class='sg-step'><div class='sg-step-n'>{n}</div>"
            f"<div class='sg-step-t'>{text}</div></div>")


def _group(title: str, sub: str, sections: list[str]) -> str:
    return (f"<div class='sg-gh'><span>{title}</span><small>{sub}</small></div>"
            "<div class='sg-list'>" + ''.join(sections) + "</div>")


def _f(s: str) -> str:
    """A formula / code fragment, kept left-to-right."""
    return f"<code dir='ltr'>{s}</code>"


G, R, B, A = "#1B7A36", "#C1121F", "#0063D1", "#A15C00"


def _c(txt: str, col: str) -> str:
    return f"<b style='color:{col}'>{txt}</b>"


_AR_LETTERS = "أبجدهوزحطيكلمن"


def _ideas_group(ideas: list[tuple[str, str]]) -> str:
    """«الفكرة والمنطق» group: lettered sections (أ، ب، ج…) so they never clash
    with the numbered reading / programmer sections."""
    secs = [_sec(_AR_LETTERS[i], title, body) for i, (title, body) in enumerate(ideas)]
    return _group('الفكرة والمنطق', 'ليه كل جزء اتعمل كده، المنطق وراه، اتطبق إزاي، وبأي شروط', secs)


